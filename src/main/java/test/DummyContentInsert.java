	public static void main(String[] args) throws Exception {
		if (args.length > 0 && args[0].equals("delete")) {
			delete();
			return;
		}

		FaqDao faqDao = new FaqDao();
		int faqOk = 0;
		int sort = 10;
		for (String[] f : FAQS) {
			FaqDto dto = new FaqDto();
			dto.setCategory(f[0]);
			dto.setQuestion(esc(f[1]));
			dto.setAnswer(esc(f[2]));
			dto.setSort_no(sort);
			dto.setUse_yn("Y");
			dto.setReg_id(REG_ID);
			if (faqDao.faqSave(dto) == 1) faqOk++;
			sort += 10;
		}

		NoticeDao noticeDao = new NoticeDao();
		Random r = new Random(20260923);
		int noticeOk = 0;
		for (int i = NOTICES.length - 1; i >= 0; i--) {
			String[] n = NOTICES[i];
			NoticeDto dto = new NoticeDto();
			dto.setTitle(esc(n[0]));
			dto.setContent(esc(n[1]));
			dto.setImportant(n[2]);
			dto.setAttach("");
			dto.setReg_id(REG_ID);
			dto.setReg_date(n[3]);
			if (noticeDao.noticeSave(dto) == 1) {
				setHit(dto.getNo(), 20 + r.nextInt(300));
				noticeOk++;
			}
		}
		System.out.println("FAQ " + faqOk + "건 / 공지 " + noticeOk + "건 등록");
	}

